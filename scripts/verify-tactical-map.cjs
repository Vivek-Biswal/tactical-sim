const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
for (const ext of ['.ts','.tsx']) require.extensions[ext] = (module, filename) => {
  const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true, target: ts.ScriptTarget.ES2021, jsx: ts.JsxEmit.ReactJSX } });
  module._compile(compiled.outputText, filename);
};
const { LocalSimulationEngine } = require('../src/simulation/lib/simulation.ts');
const { clampPoint, gridReference } = require('../src/simulation/lib/mapGeometry.ts');
const engine = new LocalSimulationEngine('map-test');
const alpha = state => state.trueUnits.find(u=>u.id==='unit-alpha');
try {
  assert.equal(engine.moveTeam('unit-alpha', {x:320,y:380}), false, 'pending exercises cannot move teams');
  engine.start(); engine.dispose();
  assert.equal(engine.moveTeam('contact-1', {x:320,y:380}), false, 'unknown contacts cannot be commanded');
  assert.equal(engine.moveTeam('unit-alpha', {x:NaN,y:380}), false, 'invalid destinations are rejected');
  const initialAlpha = alpha(engine.getState());
  const firstDestination = {x:initialAlpha.x+100,y:initialAlpha.y};
  assert.equal(engine.moveTeam('unit-alpha', firstDestination), true);
  engine.tick(1);
  assert.equal(alpha(engine.getState()).x, initialAlpha.x+10, 'movement advances by simulation time rather than teleporting');
  assert.equal(alpha(engine.getState()).status, 'moving');
  engine.pause(); engine.tick(5);
  assert.equal(alpha(engine.getState()).x, initialAlpha.x+10, 'pause freezes movement');
  engine.resume(); engine.tick(9);
  assert.equal(alpha(engine.getState()).x, firstDestination.x);
  assert.equal(alpha(engine.getState()).status, 'operational', 'arrival resolves movement status');
  assert.equal(alpha(engine.getState()).destination, undefined);
  assert.ok(engine.generateAAR().fullEventLog.some(e=>e.title==='Team Arrived'));
  engine.moveTeam('unit-alpha', {x:firstDestination.x+100,y:firstDestination.y});
  engine.applyInstructorInject('outdate_map');
  const snapshot = engine.getState().units;
  engine.tick(2);
  assert.deepEqual(engine.getState().units, snapshot, 'outdated feed hides ongoing movement');
  assert.equal(alpha(engine.getState()).x, firstDestination.x+20, 'ground truth continues during feed loss');
  assert.equal(engine.moveTeam('unit-alpha', {x:500,y:380}), false);
  engine.applyInstructorInject('unavailable_map');
  engine.tick(1);
  engine.applyInstructorInject('restore_map');
  assert.equal(engine.getState().units.find(u=>u.id==='unit-alpha').x, firstDestination.x+30, 'restore catches up to actual movement');
  engine.reset();
  assert.equal(alpha(engine.getState()).destination, undefined);
  engine.start();engine.dispose();
  engine.tick(30);
  engine.applyInstructorInject('outdate_map');
  const knownActivities=engine.getState().activityMarkers;
  engine.tick(10);
  assert.deepEqual(engine.getState().activityMarkers,knownActivities,'stale feed freezes newly detected activity');
  engine.applyInstructorInject('restore_map');
  assert.ok(engine.getState().activityMarkers.some(m=>m.type==='contact_warning'),'restoration synchronizes newly detected activity');
  engine.reset();engine.start();engine.dispose();
  for(let i=0;i<55;i++)engine.tick(1);
  assert.ok(engine.getState().activityMarkers.some(m=>m.type==='contact_warning'));
  assert.ok(engine.getState().activityMarkers.some(m=>m.type==='hostile_jammer'));
  engine.applyInstructorInject('outdate_map');
  const markers=engine.getState().activityMarkers;
  for(let i=55;i<111;i++){if(engine.getState().status==='paused')engine.resume();engine.tick(1);}
  // Scenario restores its feed at 110 seconds; force stale before testing the final marker update.
  engine.applyInstructorInject('restore_map');
  assert.ok(engine.getState().activityMarkers.some(m=>m.id==='jammer-7'&&m.status==='cleared'));
  assert.ok(markers.some(m=>m.id==='jammer-7'&&m.status==='high_threat'));
  assert.deepEqual(clampPoint({x:900,y:-10}),{x:800,y:0});
  assert.equal(gridReference({x:800,y:600}),'P12');
  assert.equal(gridReference({x:0,y:0}),'A1');
  const React = require('react');
  const {renderToStaticMarkup}=require('react-dom/server');
  const {TacticalMap}=require('../src/simulation/components/tactical/TacticalMap.tsx');
  const state=engine.getState();
  const props={units:state.units,activityMarkers:state.activityMarkers,mapLastUpdated:'Test snapshot'};
  const current=renderToStaticMarkup(React.createElement(TacticalMap,{...props,mapStatus:'current'}));
  assert.match(current,/CURRENT/);
  assert.match(current,/Select Army Team Alpha/);
  assert.match(current,/Inspect Route checkpoint/);
  const stale=renderToStaticMarkup(React.createElement(TacticalMap,{...props,mapStatus:'outdated'}));
  assert.match(stale,/OUTDATED/);
  assert.match(stale,/Last known positions/);
  const unavailable=renderToStaticMarkup(React.createElement(TacticalMap,{...props,mapStatus:'unavailable'}));
  assert.match(unavailable,/MAP UNAVAILABLE/);
  assert.doesNotMatch(unavailable,/Select Army Team Alpha/);
  assert.doesNotMatch(unavailable,/Inspect Checkpoint/);
  assert.match(unavailable,/MAIN HIGHWAY ROUTE/, 'static terrain stays visible');
  const pair=renderToStaticMarkup(React.createElement('div',null,React.createElement(TacticalMap,props),React.createElement(TacticalMap,props)));
  const ids=[...pair.matchAll(/\sid="([^"]+)"/g)].map(m=>m[1]);
  assert.equal(new Set(ids).size,ids.length,'SVG definition IDs are unique across multiple maps');
  console.log('PASS: movement/arrival/pause, destination guards, stale/restore, scenario activity, map bounds, status rendering, unavailable data hiding, unique SVG IDs');
} finally {engine.dispose();}
